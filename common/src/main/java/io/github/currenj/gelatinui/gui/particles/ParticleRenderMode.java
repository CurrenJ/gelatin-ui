package io.github.currenj.gelatinui.gui.particles;

/**
 * Defines how a particle should be rendered.
 */
public enum ParticleRenderMode {
    /**
     * Render as a 2D sprite texture.
     */
    SPRITE,
    
    /**
     * Render as a 3D Minecraft itemstack with full rotation support.
     */
    ITEMSTACK
}
